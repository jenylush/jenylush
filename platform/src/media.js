// Photo processing and private storage. Uploads are decoded with sharp (which also
// validates that the file really is an image), auto-rotated, stripped of metadata
// such as GPS location, and stored as responsive WebP variants outside the public
// web root. Files are only served through an access-checked route.

import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

export const VARIANTS = [400, 1200, 2000];
export const ACCEPTED_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'image/avif', 'image/gif', 'image/heic', 'image/heif'];
const ACCEPTED_FORMATS = new Set(['jpeg', 'png', 'webp', 'avif', 'gif', 'heif']);

export class MediaError extends Error { constructor(message) { super(message); this.status = 400; } }

export function mediaDir(dataDir, weddingId, assetId) {
  // IDs are UUIDs generated by the server; double-check to rule out path traversal.
  if (!/^[a-f0-9-]{36}$/.test(weddingId) || !/^[a-f0-9-]{36}$/.test(assetId)) throw new Error('Invalid media id');
  return path.join(dataDir, 'media', weddingId, assetId);
}

export async function processImage(buffer) {
  let meta;
  try {
    meta = await sharp(buffer, { failOn: 'error' }).metadata();
  } catch {
    throw new MediaError('That file could not be read as an image. Please upload a JPEG, PNG, WebP or HEIC photo.');
  }
  if (!ACCEPTED_FORMATS.has(meta.format)) throw new MediaError(`${String(meta.format || 'This').toUpperCase()} files are not supported. Please upload a JPEG, PNG, WebP or HEIC photo.`);
  if ((meta.width || 0) * (meta.height || 0) > 80e6) throw new MediaError('That image is too large (over 80 megapixels).');
  const base = sharp(buffer, { failOn: 'error' }).rotate(); // apply EXIF orientation; metadata is dropped by default
  const outputs = {};
  let width = null, height = null;
  for (const size of VARIANTS) {
    const { data, info } = await base.clone().resize({ width: size, height: size, fit: 'inside', withoutEnlargement: true }).webp({ quality: size >= 2000 ? 82 : 78 }).toBuffer({ resolveWithObject: true });
    outputs[size] = data;
    if (size === 2000) { width = info.width; height = info.height; }
  }
  const bytes = Object.values(outputs).reduce((n, b) => n + b.length, 0);
  return { outputs, width, height, bytes };
}

export function writeVariants(dataDir, weddingId, assetId, outputs) {
  const dir = mediaDir(dataDir, weddingId, assetId);
  fs.mkdirSync(dir, { recursive: true });
  for (const [size, buf] of Object.entries(outputs)) {
    const tmp = path.join(dir, `${size}.webp.tmp`);
    fs.writeFileSync(tmp, buf);
    fs.renameSync(tmp, path.join(dir, `${size}.webp`));
  }
}

export function variantPath(dataDir, weddingId, assetId, size) {
  const s = VARIANTS.includes(Number(size)) ? Number(size) : 1200;
  return path.join(mediaDir(dataDir, weddingId, assetId), `${s}.webp`);
}

export function deleteAssetFiles(dataDir, weddingId, assetId) {
  fs.rmSync(mediaDir(dataDir, weddingId, assetId), { recursive: true, force: true });
}

export function deleteWeddingFiles(dataDir, weddingId) {
  if (!/^[a-f0-9-]{36}$/.test(weddingId)) return;
  fs.rmSync(path.join(dataDir, 'media', weddingId), { recursive: true, force: true });
}
